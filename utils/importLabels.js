const lookup = (dict, sheetKey, key) =>
  dict[`${sheetKey}.${key}`] ?? dict[key] ?? COMMON[`${sheetKey}.${key}`] ?? COMMON[key] ?? null;

/** เติม label_en ให้คอลัมน์ของ sheet และ name_en ให้ sheet — คืนสำเนา ไม่แก้ของเดิม */
const withEnSheet = (template, sheet) => {
  const dict = TEMPLATES[template] || {};
  return {
    ...sheet,
    name_en: dict[`sheet:${sheet.key}`] ?? sheet.name_en ?? sheet.name,
    columns: (sheet.columns || []).map(c => ({ ...c, label_en: c.label_en ?? lookup(dict, sheet.key, c.key) ?? c.label })),
  };
};

const withEnSheets = (template, sheets) => sheets.map(s => withEnSheet(template, s));

/** ?lang=en ของ request ดาวน์โหลดเทมเพลต */
const isEnglishReq = (req) => String(req.query?.lang || '').toLowerCase() === 'en';

/** แถวคำอธิบายในไฟล์เทมเพลต "(ชื่อคอลัมน์ *)" — ตามภาษา; รูปแบบวงเล็บใช้แยกแถวคำอธิบายออกจากข้อมูลตอนอ่านไฟล์ */
const labelRow = (columns, english) =>
  columns.map(c => `(${(english ? c.label_en : null) || c.label}${c.required ? ' *' : ''})`);

const colWidths = (columns, english) =>
  columns.map(c => ({ wch: Math.max(c.key.length, ((english ? c.label_en : null) || c.label).length) + 4 }));

module.exports = { withEnSheet, withEnSheets, isEnglishReq, labelRow, colWidths };
